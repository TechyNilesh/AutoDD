"""
Meta-ADD Pre-training Pipeline

This script pre-trains the Meta-ADD prototypical network using error rate sequences
generated by applying a Hoeffding Tree classifier to synthetic data streams.

Based on the paper's approach:
1. Generate synthetic streams with different drift types (2000 per type)
2. Apply Hoeffding Tree classifier to each stream
3. Extract error sequences and compute gap meta-features
4. Train prototypical network to classify drift types
5. Save pre-trained model

Usage:
    python -m MetaADD.pretrain
    python -m MetaADD.pretrain --n_streams 500 --output pretrained_model.pt
"""

