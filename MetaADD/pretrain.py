# Drift type labels
DRIFT_TYPES = {
    'normal': 0,
    'sudden': 1,
    'gradual': 2,
    'incremental': 3
}


def generate_error_sequence_direct(
    drift_type: str,
    n_samples: int = 5000,
    seed: int = 42
) -> List[float]:
    """
    Generate error sequence directly by simulating drift patterns.

    This avoids the math overflow issues with ConceptDriftStream by
    directly generating error sequences that mimic different drift types.

    Parameters
    ----------
    drift_type : str
        Type of drift: 'normal', 'sudden', 'gradual', 'incremental'
    n_samples : int
        Number of samples in the stream
    seed : int
        Random seed

    Returns
    -------
    errors : list of float
        Binary error sequence
    """
    np.random.seed(seed)
    errors = []

    if drift_type == 'normal':
        # No drift - stable error rate
        base_error_rate = np.random.uniform(0.1, 0.3)
        for _ in range(n_samples):
            errors.append(float(np.random.random() < base_error_rate))

    elif drift_type == 'sudden':
        # Sudden drift - abrupt change in error rate
        drift_point = np.random.randint(n_samples // 3, 2 * n_samples // 3)
        error_rate_before = np.random.uniform(0.1, 0.25)
        error_rate_after = np.random.uniform(0.35, 0.55)

        for i in range(n_samples):
            if i < drift_point:
                errors.append(float(np.random.random() < error_rate_before))
            else:
                errors.append(float(np.random.random() < error_rate_after))

    elif drift_type == 'gradual':
        # Gradual drift - slow transition between error rates
        drift_start = np.random.randint(n_samples // 4, n_samples // 2)
        drift_width = np.random.randint(n_samples // 4, n_samples // 2)
        drift_end = min(drift_start + drift_width, n_samples - 1)

        error_rate_before = np.random.uniform(0.1, 0.25)
        error_rate_after = np.random.uniform(0.35, 0.55)

        for i in range(n_samples):
            if i < drift_start:
                rate = error_rate_before
            elif i > drift_end:
                rate = error_rate_after
            else:
                # Linear interpolation
                progress = (i - drift_start) / max(drift_end - drift_start, 1)
                rate = error_rate_before + progress * (error_rate_after - error_rate_before)
            errors.append(float(np.random.random() < rate))

    elif drift_type == 'incremental':
        # Incremental drift - continuous slow change
        error_rate_start = np.random.uniform(0.1, 0.2)
        error_rate_end = np.random.uniform(0.4, 0.55)

        for i in range(n_samples):
            progress = i / n_samples
            rate = error_rate_start + progress * (error_rate_end - error_rate_start)
            # Add some noise
            rate += np.random.uniform(-0.03, 0.03)
            rate = np.clip(rate, 0.05, 0.95)
            errors.append(float(np.random.random() < rate))

    else:
        raise ValueError(f"Unknown drift type: {drift_type}")

    return errors


def generate_stream_with_classifier(
    drift_type: str,
    n_samples: int = 5000,
    seed: int = 42
) -> List[float]:
    """
    Generate error sequence using River streams and Hoeffding Tree classifier.
    Falls back to direct generation if stream causes overflow.

    Parameters
    ----------
    drift_type : str
        Type of drift: 'normal', 'sudden', 'gradual', 'incremental'
    n_samples : int
        Number of samples in the stream
    seed : int
        Random seed

    Returns
    -------
    errors : list of float
        Binary error sequence
    """
    np.random.seed(seed)

    try:
        # Use different base streams for variety
        base_variant = seed % 4

        if drift_type == 'normal':
            # No drift - stationary stream
            stream = synth.SEA(variant=base_variant, seed=seed)

        elif drift_type == 'sudden':
            # Use Agrawal for sudden drift (more stable)
            stream = synth.Agrawal(
                classification_function=(seed % 5),
                seed=seed,
                perturbation=0.1
            )

        elif drift_type == 'gradual':
            # Use mixed stream approach
            stream = synth.Mixed(
                classification_functions=[seed % 2, (seed + 1) % 2],
                seed=seed
            )

        elif drift_type == 'incremental':
            # Use Hyperplane for incremental drift
            stream = synth.Hyperplane(
                seed=seed,
                n_features=10,
                n_drift_features=3,
                mag_change=0.005,
                noise_percentage=0.05
            )
        else:
            raise ValueError(f"Unknown drift type: {drift_type}")

        # Extract error sequence using classifier
        classifier = tree.HoeffdingTreeClassifier()
        errors = []

        for i, (x, y) in enumerate(stream.take(n_samples)):
            y_pred = classifier.predict_one(x)
            if y_pred is not None:
                error = 0.0 if y_pred == y else 1.0
            else:
                error = 1.0
            errors.append(error)
            classifier.learn_one(x, y)

        return errors

    except (OverflowError, ValueError) as e:
        # Fall back to direct error sequence generation
        return generate_error_sequence_direct(drift_type, n_samples, seed)


def generate_training_data(
    n_streams_per_type: int = 2000,
    n_samples_per_stream: int = 5000,
    use_classifier: bool = False,
    save_path: str = None,
    verbose: bool = True
) -> List[Tuple[List[float], int]]:
    """
    Generate training data for Meta-ADD pre-training.

    Creates error sequences that simulate different types of concept drift.
    Can optionally use River streams with classifier or generate directly.

    Parameters
    ----------
    n_streams_per_type : int
        Number of streams to generate per drift type (4 types total)
    n_samples_per_stream : int
        Number of samples per stream
    use_classifier : bool
        If True, use River streams with Hoeffding Tree classifier.
        If False (default), generate error sequences directly (faster, more stable).
    save_path : str, optional
        Path to save training data as JSON. If None, data is not saved.
    verbose : bool
        Whether to print progress

    Returns
    -------
    training_data : list of (error_sequence, drift_type_label) tuples
    """
    training_data = []

    total_streams = n_streams_per_type * len(DRIFT_TYPES)

    if verbose:
        print(f"Generating {total_streams} training streams...")
        print(f"  {n_streams_per_type} streams per drift type")
        print(f"  {n_samples_per_stream} samples per stream")
        print(f"  Method: {'classifier' if use_classifier else 'direct generation'}")
        print()

    for drift_type, label in DRIFT_TYPES.items():
        if verbose:
            print(f"Generating {drift_type} streams (label={label})...")

        for i in range(n_streams_per_type):
            seed = label * 10000 + i

            # Generate error sequence
            if use_classifier:
                errors = generate_stream_with_classifier(
                    drift_type=drift_type,
                    n_samples=n_samples_per_stream,
                    seed=seed
                )
            else:
                errors = generate_error_sequence_direct(
                    drift_type=drift_type,
                    n_samples=n_samples_per_stream,
                    seed=seed
                )

            training_data.append((errors, label))

            if verbose and (i + 1) % 100 == 0:
                print(f"  Generated {i + 1}/{n_streams_per_type} streams")

        if verbose:
            print(f"  Completed {drift_type} streams")

    # Save training data if path provided
    if save_path is not None:
        import json
        save_data = {
            'n_streams_per_type': n_streams_per_type,
            'n_samples_per_stream': n_samples_per_stream,
            'drift_types': DRIFT_TYPES,
            'data': [(errors, label) for errors, label in training_data]
        }
        with open(save_path, 'w') as f:
            json.dump(save_data, f)
        if verbose:
            print(f"\nTraining data saved to: {save_path}")

    return training_data


def load_training_data(path: str) -> List[Tuple[List[float], int]]:
    """
    Load pre-generated training data from JSON file.

    Parameters
    ----------
    path : str
        Path to the training data JSON file.

    Returns
    -------
    training_data : list of (error_sequence, drift_type_label) tuples
    """
    import json
    with open(path, 'r') as f:
        save_data = json.load(f)
    return [(errors, label) for errors, label in save_data['data']]


def pretrain_meta_add(
    n_streams_per_type: int = 1250,  # Paper: 1250 per type (5000 total for training)
    n_samples_per_stream: int = 2000,  # Paper: 2000 instances per stream
    window_size: int = 50,  # Paper Table 2: n=50 gives best accuracy (94.56%)
    n_meta_features: int = 100,  # Paper: l=100
    embedding_dim: int = 128,
    n_epochs: int = 100,
    learning_rate: float = 1e-3,  # Paper: Adam with lr=10^-3
    output_path: str = None,
    save_data_path: str = None,
    use_classifier: bool = False,
    verbose: bool = True
) -> PrototypicalNetwork:
    """
    Pre-train Meta-ADD prototypical network.

    Parameters
    ----------
    n_streams_per_type : int
        Number of streams per drift type
    n_samples_per_stream : int
        Samples per stream
    window_size : int
        Window size for gap computation
    n_meta_features : int
        Number of gap meta-features
    embedding_dim : int
        Embedding dimension
    n_epochs : int
        Training epochs
    learning_rate : float
        Learning rate
    output_path : str, optional
        Path to save pre-trained model
    save_data_path : str, optional
        Path to save generated training data as JSON
    use_classifier : bool
        If True, use River streams with classifier (slower but more realistic)
    verbose : bool
        Whether to print progress

    Returns
    -------
    model : PrototypicalNetwork
        Pre-trained model
    """
    start_time = time.time()

    # Validate parameters
    min_samples_needed = (n_meta_features + 1) * window_size
    if n_samples_per_stream < min_samples_needed:
        raise ValueError(
            f"n_samples_per_stream ({n_samples_per_stream}) must be >= "
            f"(n_meta_features + 1) * window_size = {min_samples_needed}. "
            f"Increase n_samples or decrease n_meta_features/window_size."
        )

    if verbose:
        print("=" * 60)
        print("Meta-ADD Pre-training Pipeline")
        print("=" * 60)
        print()

    # Step 1: Generate training data
    training_data = generate_training_data(
        n_streams_per_type=n_streams_per_type,
        n_samples_per_stream=n_samples_per_stream,
        use_classifier=use_classifier,
        save_path=save_data_path,
        verbose=verbose
    )

    if verbose:
        print(f"\nGenerated {len(training_data)} training streams")
        print(f"Data generation time: {time.time() - start_time:.1f}s")
        print()

    # Step 2: Train prototypical network
    train_start = time.time()

    if verbose:
        print("Training prototypical network...")

    model = train_meta_detector(
        training_streams=training_data,
        window_size=window_size,
        n_meta_features=n_meta_features,
        embedding_dim=embedding_dim,
        n_epochs=n_epochs,
        learning_rate=learning_rate,
        verbose=verbose
    )

    if verbose:
        print(f"\nTraining time: {time.time() - train_start:.1f}s")
        print(f"Total time: {time.time() - start_time:.1f}s")

    # Step 3: Save model
    if output_path is None:
        output_path = os.path.join(
            os.path.dirname(os.path.abspath(__file__)),
            "pretrained_model.pt"
        )

    model.save(output_path)

    if verbose:
        print(f"\nModel saved to: {output_path}")
        print("=" * 60)

    return model


def quick_pretrain(output_path: str = None, verbose: bool = True) -> PrototypicalNetwork:
    """
    Quick pre-training with reduced parameters for testing.

    Uses fewer streams and samples for faster training.
    Suitable for testing or when computational resources are limited.

    Parameters
    ----------
    output_path : str, optional
        Path to save model
    verbose : bool
        Whether to print progress

    Returns
    -------
    model : PrototypicalNetwork
        Pre-trained model
    """
    # Paper params but with fewer streams for quick testing
    # window_size=1, n_meta_features=100 (paper's n=1, l=100)
    return pretrain_meta_add(
        n_streams_per_type=100,  # Reduced for quick training
        n_samples_per_stream=2000,  # Paper: 2000
        window_size=1,  # Paper: n=1
        n_meta_features=100,  # Paper: l=100
        n_epochs=50,
        output_path=output_path,
        verbose=verbose
    )


def load_pretrained_model(path: str = None) -> PrototypicalNetwork:
    """
    Load a pre-trained Meta-ADD model.

    Parameters
    ----------
    path : str, optional
        Path to model file. Defaults to 'pretrained_model.pt' in MetaADD folder.

    Returns
    -------
    model : PrototypicalNetwork
        Loaded model
    """
    if path is None:
        path = os.path.join(
            os.path.dirname(os.path.abspath(__file__)),
            "pretrained_model.pt"
        )

    return PrototypicalNetwork.load(path)


